function Visualizer() {
  const [overviewOpen, setOverviewOpen] = useState(false);
  const [filter, setFilter] = useState("all");

  const filtered = filter === "all"
    ? ALL_QUESTIONS
    : ALL_QUESTIONS.filter(q => q.category === filter);

  const categories = ["all", "True/False", "Circuit Action", "Self-Test"];

  return (
    <div>
      <ChapterOverview expanded={overviewOpen} onToggle={() => setOverviewOpen(!overviewOpen)} />

      <div style={{ display: "flex", gap: "8px", marginBottom: "20px", flexWrap: "wrap" }}>
        {categories.map(cat => (
          <button key={cat} onClick={() => setFilter(cat)} style={{
            padding: "7px 16px",
            borderRadius: "8px",
            border: `1px solid ${filter === cat ? theme.accent : theme.border}`,
            background: filter === cat ? "rgba(108,159,255,0.12)" : theme.surface,
            color: filter === cat ? theme.accent : theme.textMuted,
            cursor: "pointer",
            fontSize: "13px",
            fontWeight: 600,
            fontFamily: "inherit",
            transition: "all 0.15s",
          }}>{cat === "all" ? `All (${ALL_QUESTIONS.length})` : `${cat} (${ALL_QUESTIONS.filter(q => q.category === cat).length})`}</button>
        ))}
      </div>

      <div style={{ display: "flex", flexDirection: "column", gap: "8px" }}>
        {filtered.map((q, i) => <QuestionCard key={q.id} q={q} index={i} />)}
      </div>
    </div>
  );
}

