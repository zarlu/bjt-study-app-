function TestMode({ onBack }) {
  const [category, setCategory] = useState(null);
  const [questions, setQuestions] = useState([]);
  const [currentIndex, setCurrentIndex] = useState(0);
  const [answers, setAnswers] = useState([]);
  const [phase, setPhase] = useState("select"); // select, testing, results

  const startTest = (cat) => {
    setCategory(cat);
    let pool;
    if (cat === "all") pool = ALL_QUESTIONS;
    else pool = ALL_QUESTIONS.filter(q => q.category === cat);
    setQuestions(shuffle(pool));
    setAnswers([]);
    setCurrentIndex(0);
    setPhase("testing");
  };

  const handleAnswer = (correct) => {
    const newAnswers = [...answers, correct];
    setAnswers(newAnswers);
    if (currentIndex + 1 >= questions.length) {
      setTimeout(() => setPhase("results"), 200);
    } else {
      setTimeout(() => setCurrentIndex(currentIndex + 1), 200);
    }
  };

  if (phase === "select") return <TestCategorySelect onSelect={startTest} />;
  if (phase === "results") return (
    <TestResults
      questions={questions}
      answers={answers}
      onRestart={() => startTest(category)}
      onMenu={() => setPhase("select")}
    />
  );

  return (
    <TestQuestion
      key={currentIndex}
      q={questions[currentIndex]}
      qIndex={currentIndex}
      total={questions.length}
      onAnswer={handleAnswer}
    />
  );
}

